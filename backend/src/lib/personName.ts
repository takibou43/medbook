import { z } from "zod";

/**
 * اسم/لقب شخص: نمنع فقط المحارف التي تُستغل لحقن HTML/JS (< > " & ` \) ومحارف التحكم،
 * ونسمح بغير ذلك (أحرف، أرقام، مسافة، شرطة، نقطة، فاصلة عليا...) حتى لا نرفض أسماء مشروعة.
 * هذا دفاع بالعمق؛ الحماية الأساسية هي ترميز المخرجات عند العرض (escapeHtml).
 */
export const PERSON_NAME_REGEX = /^[^<>"&`\\\x00-\x1f\x7f]+$/;

export const personName = (minMsg = "النص قصير جدًا", max = 60) =>
  z
    .string()
    .trim()
    .min(2, minMsg)
    .max(max, `النص طويل جدًا (${max} حرفًا كحد أقصى)`)
    .regex(PERSON_NAME_REGEX, "الاسم يحتوي محارف غير مسموحة (< > \" & `)");
