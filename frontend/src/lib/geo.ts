export function haversineKm(lat1: number, lng1: number, lat2: number, lng2: number): number {
  const R = 6371;
  const toRad = (v: number) => (v * Math.PI) / 180;
  const dLat = toRad(lat2 - lat1);
  const dLng = toRad(lng2 - lng1);
  const a = Math.sin(dLat / 2) ** 2 + Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(a));
}

export interface DoctorDistance {
  km: number;
  // true = محسوبة من إحداثيات عيادة الطبيب نفسها؛ false = تقريبية من مركز ولايته (للترتيب فقط).
  exact: boolean;
}

// مسافة الطبيب عن موقع المريض بلا أي طلب إضافي للخادم — نستعمل الإحداثيات التي يرجعها
// /doctors أصلًا، وإن غابت نرجع إلى مركز الولاية للترتيب فقط (لا تُعرض للمريض كرقم دقيق).
export function distanceToDoctor(d: Doctor, pos: { lat: number; lng: number }): DoctorDistance | null {
  if (d.latitude != null && d.longitude != null) {
    return { km: haversineKm(pos.lat, pos.lng, d.latitude, d.longitude), exact: true };
  }
  const c = WILAYA_CENTROIDS[d.wilaya.code];
  if (!c) return null;
  return { km: haversineKm(pos.lat, pos.lng, c.lat, c.lng), exact: false };
}
